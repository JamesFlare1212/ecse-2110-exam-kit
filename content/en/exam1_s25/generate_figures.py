            wire(ax,outer,pos);flow(ax,outer,pos);node(ax,pos)
            text(ax, (outer[0],outer[1]+(.3 if name==r'$a$' else -.28)),name)
            if name==r'$a$': text(ax,(outer[0]+.45,3.15),current)
