def board(dark):
    p.setup(dark)
    fig, ax = p.plt.subplots(figsize=(10, 4.8))
    ax.set(xlim=(-.5, 10), ylim=(-1.8, 4.1))
    ax.axis('off')
    return fig, ax


def wire(ax, a, b, **kw):
    ax.plot([a[0], b[0]], [a[1], b[1]], color=p.INK, lw=1.8, **kw)


def text(ax, xy, s, **kw):
    ax.text(*xy, s, ha=kw.pop('ha', 'center'), va='center', fontsize=kw.pop('fontsize', 11),
            color=p.INK, **kw)


def flow(ax, a, b):
    ax.add_patch(FancyArrowPatch(a, b, arrowstyle='-|>', mutation_scale=14,
                               color=p.ORANGE, lw=1.7))


def box(ax, a, b):
    """IEC impedance rectangle; wires end at the box, never through its label."""
    a, b = np.array(a, dtype=float), np.array(b, dtype=float)
    u = (b-a)/np.linalg.norm(b-a)
    normal = np.array([-u[1], u[0]])
    mid = (a+b)/2
    left, right = mid-u*.40, mid+u*.40
    wire(ax, a, left); wire(ax, right, b)
    points = [left+normal*.15, right+normal*.15, right-normal*.15, left-normal*.15, left+normal*.15]
    xy = np.array(points)
    ax.plot(xy[:, 0], xy[:, 1], color=p.INK, lw=1.8)


def node(ax, xy):
    ax.add_patch(Circle(xy, .045, color=p.INK))


def source(ax, a, b, name, label_offset=(0, 0)):
    a, b = np.array(a, float), np.array(b, float)
    u = (b-a)/np.linalg.norm(b-a); mid=(a+b)/2
    wire(ax, a, mid-u*.24); wire(ax, mid+u*.24, b)
    ax.add_patch(Circle(mid, .24, ec=p.INK, fc=p.PAPER, lw=1.7))
    text(ax, mid+np.array(label_offset), name, fontsize=9)


